// Simple JavaScript code
function greet(name) {
    return `Hello, ${name}!`;
}

console.log(greet("World"));

// Simple arithmetic
const sum = (a, b) => a + b;
console.log(sum(5, 3)); // Output: 8

// Simple array operation
const numbers = [1, 2, 3, 4, 5];
const doubled = numbers.map(num => num * 2);
console.log(doubled); // Output: [2, 4, 6, 8, 10]